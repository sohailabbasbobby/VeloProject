    mot_expiry DATE,
    phv_expiry DATE,                                     -- PCO / PHV licence
    insurance_expiry DATE,
    road_tax_expiry DATE,
    mot_document_url VARCHAR(512),
    insurance_document_url VARCHAR(512),
    photo_url VARCHAR(512),
    current_location GEOMETRY(Point, 4326),
    -- Lease tracking
    lease_provider VARCHAR(150),
    lease_start_date DATE,
    lease_end_date DATE,
    lease_total_cost NUMERIC(12,2),
    lease_paid_to_date NUMERIC(12,2) NOT NULL DEFAULT 0,
