-- ------------------------------------------------------------------------------------
-- 6. TRIPS / JOBS — BOOKING LIFECYCLE, OWN-FLEET-FIRST, POOL, NEGOTIATION
-- ------------------------------------------------------------------------------------
CREATE TYPE trip_channel AS ENUM ('OWN_APP','POOL','CORPORATE');
CREATE TYPE trip_state AS ENUM (
    'PENDING_DISPATCH',      -- created, custom price set, not yet offered
    'OFFERING_OWN_FLEET',    -- own-fleet-first window active
    'IN_POOL',               -- dropped into shared cross-tenant pool
    'NEGOTIATION',           -- counter-offer countdown active
    'ASSIGNED',              -- accepted by a driver/tenant
    'DRIVER_EN_ROUTE',
    'ARRIVED',
    'IN_PROGRESS',
    'COMPLETED',
    'CANCELLED',
    'EXPIRED'
);
CREATE TYPE trip_cancellation_approver AS ENUM ('N/A','PENDING','ADMIN_APPROVED','ADMIN_REJECTED');

CREATE TABLE trips (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    task_id VARCHAR(30) UNIQUE NOT NULL,                 -- human display ID e.g. 'VLT-8F2K1'
    tenant_id UUID NOT NULL REFERENCES tenants(id),      -- originating tenant
    channel trip_channel NOT NULL DEFAULT 'OWN_APP',
    state trip_state NOT NULL DEFAULT 'PENDING_DISPATCH',
    -- Pricing (§1.2: fully custom-entered per trip; no flat fee schedule)
    custom_price NUMERIC(10,2) NOT NULL CHECK (custom_price > 0),
    pool_floor_price NUMERIC(10,2),                      -- computed network floor at publish time
    negotiated_price NUMERIC(10,2),                      -- active counter-offer amount
    final_price NUMERIC(10,2),
    platform_fee_net NUMERIC(10,2) NOT NULL DEFAULT 0,
    finder_margin_net NUMERIC(10,2) NOT NULL DEFAULT 0,  -- originating tenant's finder's margin
    driver_earnings NUMERIC(10,2),
    tip NUMERIC(10,2) NOT NULL DEFAULT 0,
    -- Route
    pickup_address TEXT NOT NULL,
    pickup_lat DOUBLE PRECISION,
    pickup_lng DOUBLE PRECISION,
    pickup_geom GEOMETRY(Point, 4326),
    dropoff_address TEXT NOT NULL,
    dropoff_lat DOUBLE PRECISION,
    dropoff_lng DOUBLE PRECISION,
    dropoff_geom GEOMETRY(Point, 4326),
    distance_miles NUMERIC(8,2),
    duration_minutes INT,
    -- Schedule
    booking_type VARCHAR(20) NOT NULL DEFAULT 'ASAP',    -- ASAP|SCHEDULED
    scheduled_at TIMESTAMPTZ,
    accepted_at TIMESTAMPTZ,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    cancellation_reason VARCHAR(255),
    cancellation_approver trip_cancellation_approver NOT NULL DEFAULT 'N/A',
    -- Parties (§3 entity separation — never conflate)
    private_client_id UUID REFERENCES private_clients(id),
    corporate_account_id UUID REFERENCES corporate_accounts(id),
    corporate_booker_name VARCHAR(150),
    passenger_name VARCHAR(150) NOT NULL,
    passenger_phone VARCHAR(50),
    passenger_count INT NOT NULL DEFAULT 1 CHECK (passenger_count > 0),
    baggage_count INT NOT NULL DEFAULT 0 CHECK (baggage_count >= 0),
    requested_tier vehicle_tier,
    -- Fulfilment
    originating_tenant_id UUID NOT NULL REFERENCES tenants(id),
    fulfilling_tenant_id UUID REFERENCES tenants(id),
    driver_id UUID REFERENCES drivers(id),
    vehicle_id UUID REFERENCES vehicles(id),
    own_fleet_deadline TIMESTAMPTZ,                      -- own-fleet-first window expiry
    conflict_acknowledged BOOLEAN NOT NULL DEFAULT FALSE,
    odometer_start INT,
    odometer_end INT,
    -- White-label display data snapshotted for cross-tenant cards (§1.3)
    originating_tenant_name VARCHAR(150),
    originating_tenant_logo_url VARCHAR(512),
    auto_pool_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_trips_tenant_state ON trips(tenant_id, state);
CREATE INDEX idx_trips_driver ON trips(driver_id);
CREATE INDEX idx_trips_pool ON trips(state) WHERE state IN ('IN_POOL','NEGOTIATION');
CREATE INDEX idx_trips_pickup_geom ON trips USING GIST (pickup_geom);
CREATE INDEX idx_trips_dropoff_geom ON trips USING GIST (dropoff_geom);

-- Own-fleet-first job offers to individual drivers (with per-driver expiry)
CREATE TABLE trip_offers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    trip_id UUID NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
    driver_id UUID NOT NULL REFERENCES drivers(id) ON DELETE CASCADE,
    tenant_id UUID NOT NULL REFERENCES tenants(id),
    offered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    response VARCHAR(20) NOT NULL DEFAULT 'PENDING',     -- PENDING|ACCEPTED|DECLINED|EXPIRED|FORFEITED_CONFLICT
    responded_at TIMESTAMPTZ
);
CREATE INDEX idx_trip_offers_driver ON trip_offers(driver_id, response);

-- B2B overflow pool mirror (jobs visible cross-tenant) + negotiation ledger
CREATE TYPE pool_job_state AS ENUM ('OPEN','NEGOTIATION','ALLOCATED','COMPLETED','WITHDRAWN');

CREATE TABLE b2b_pool_jobs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    trip_id UUID NOT NULL UNIQUE REFERENCES trips(id) ON DELETE CASCADE,
    originating_tenant_id UUID NOT NULL REFERENCES tenants(id),
    countering_tenant_id UUID REFERENCES tenants(id),
    pickup_location TEXT NOT NULL,
    pickup_geom GEOMETRY(Point, 4326) NOT NULL,
