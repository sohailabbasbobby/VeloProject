-- ====================================================================================
-- VELO PLATFORM — MASTER INITIALIZATION SCHEMA (v2)
-- Strict Multi-Tenant Architecture · PostGIS Geospatial · Full Financial Engine
--
-- APPLY ORDER MATTERS: reference tables (tenants) are created before dependents.
-- Money convention: monetary columns are NUMERIC(12,2) storing GBP pounds unless the
-- column name carries a _pence suffix (integer pence). VAT is stored alongside NET.
--
-- Entity reference codes (Global Rule 3):
--   vehicles.reference_code  = 'VLO-XXXX'
--   drivers.reference_code   = '#V-XXXX'
-- ====================================================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "postgis";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ------------------------------------------------------------------------------------
-- 1. MASTER MULTI-TENANCY CORE
-- ------------------------------------------------------------------------------------
CREATE TABLE tenants (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code VARCHAR(50) UNIQUE NOT NULL,                     -- human-readable short code
    name VARCHAR(150) NOT NULL,
    activation_status VARCHAR(50) NOT NULL DEFAULT 'REGISTRATION', -- REGISTRATION|ACTIVE|SUSPENDED|TERMINATED
    plan VARCHAR(50) NOT NULL DEFAULT 'STANDARD',
    preferred_language VARCHAR(10) DEFAULT 'en',
    vat_registered BOOLEAN NOT NULL DEFAULT FALSE,
    vat_number VARCHAR(50),
    finder_margin_rate NUMERIC(5,4) NOT NULL DEFAULT 0.2500,       -- B2B finder's margin (25% default)
    pool_accept_enabled BOOLEAN NOT NULL DEFAULT TRUE,             -- accepts pool jobs from others
    pool_min_price NUMERIC(10,2) NOT NULL DEFAULT 0.00,            -- acceptance filter: min price
    pool_vehicle_classes TEXT[] NOT NULL DEFAULT '{}',             -- acceptance filter: vehicle tiers
    pool_geo_center GEOMETRY(Point, 4326),                         -- acceptance filter: geography
    pool_geo_radius_m INT NOT NULL DEFAULT 50000,
    own_fleet_asap_timeout_s INT NOT NULL DEFAULT 60,              -- own-fleet-first window (ASAP)
    own_fleet_scheduled_timeout_m INT NOT NULL DEFAULT 10,         -- own-fleet-first window (scheduled)
    stripe_account_id VARCHAR(255),                                -- Stripe Connect express account
    stripe_payouts_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    contact_email VARCHAR(255),
    contact_phone VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

