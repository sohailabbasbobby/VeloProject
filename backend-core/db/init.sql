    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id UUID NOT NULL REFERENCES tenants(id),
    reference_code VARCHAR(20) UNIQUE NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(50),
    role VARCHAR(80) NOT NULL DEFAULT 'DISPATCHER',      -- DISPATCHER|OPERATIONS_MANAGER|FINANCE|ADMIN
    department VARCHAR(80),
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    photo_url VARCHAR(512),
    hire_date DATE,
    salary NUMERIC(10,2),
    shift_availability VARCHAR(80) DEFAULT 'Flexible',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE staff_shifts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id UUID NOT NULL REFERENCES tenants(id),
    staff_id UUID NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
    -- 30-minute granularity slots; ISO date + start/end minutes-from-midnight (0..1440, % 30 = 0)
    shift_date DATE NOT NULL,
    start_minute INT NOT NULL CHECK (start_minute % 30 = 0 AND start_minute BETWEEN 0 AND 1410),
    duration_minutes INT NOT NULL CHECK (duration_minutes % 30 = 0 AND duration_minutes > 0),
    role_assignment VARCHAR(80),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (staff_id, shift_date, start_minute)
);
CREATE INDEX idx_staff_shifts_tenant_date ON staff_shifts(tenant_id, shift_date);

