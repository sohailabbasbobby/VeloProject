-- RLS baseline: tenant isolation on tenant-owned tables. The API sets
-- `SET LOCAL app.current_tenant_id` per request/transaction (see tenant.middleware.ts).
DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'vehicles','vehicle_assignments','maintenance_logs','fleet_general_expenses','odometer_logs',
        'vehicle_issues','drivers','driver_locations','driver_shifts','chauffeur_shifts','staff','staff_shifts',
        'corporate_accounts','private_clients','trips','driver_ledgers','invoices','escrow_vault',
        'payouts','booking_expenses','driver_tips','notifications','messages','payroll_runs',
        'compliance_documents','gatekeeper_checks'
    ]
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format(
            'CREATE POLICY tenant_isolation_policy ON %I USING (tenant_id = current_setting(''app.current_tenant_id'', true)::uuid)',
            t);
    END LOOP;
END $$;

-- b2b tables: both counterparties may see rows
