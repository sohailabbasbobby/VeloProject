CREATE TYPE payment_model AS ENUM ('COMMISSION','SALARIED','CUSTOM','SUBSCRIPTION');
CREATE TYPE subscription_status AS ENUM ('NONE','ACTIVE','PAST_DUE','CANCELLED');

CREATE TABLE drivers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id UUID NOT NULL REFERENCES tenants(id),      -- primary/ employing tenant
    reference_code VARCHAR(20) UNIQUE NOT NULL,          -- '#V-XXXX' display ID
    firebase_uid VARCHAR(128) UNIQUE,
    fcm_token VARCHAR(512),
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(50),
    photo_url VARCHAR(512),
    preferred_language VARCHAR(10) DEFAULT 'en',
    -- Pay framework (§1.1)
    payment_model payment_model NOT NULL DEFAULT 'COMMISSION',
    commission_rate NUMERIC(5,2),                        -- COMMISSION: driver keeps e.g. 80.00%
    hourly_rate NUMERIC(10,2),                           -- SALARIED
    trip_bonus NUMERIC(10,2),                            -- SALARIED: flat bonus per completed trip
    custom_pay_config JSONB,                             -- CUSTOM: dynamic admin-defined structure
    subscription_status subscription_status NOT NULL DEFAULT 'NONE',
    subscription_started_at TIMESTAMPTZ,
    subscription_renews_at TIMESTAMPTZ,
    weekly_subscription_fee NUMERIC(10,2) NOT NULL DEFAULT 50.00,
    -- Compliance & licensing
    license_number VARCHAR(80),
    license_expiry DATE,
    pco_badge_number VARCHAR(80),
    pco_badge_expiry DATE,
    pco_document_url VARCHAR(512),
    id_document_url VARCHAR(512),
    right_to_work_document_url VARCHAR(512),
    compliance_status VARCHAR(30) NOT NULL DEFAULT 'PENDING', -- PENDING|VERIFIED|EXPIRING|EXPIRED|SUSPENDED
    onboarding_status VARCHAR(30) NOT NULL DEFAULT 'STARTED', -- STARTED|DOCS_UPLOADED|IN_REVIEW|VERIFIED|REJECTED
    -- Profile
    status VARCHAR(30) NOT NULL DEFAULT 'OFFLINE',       -- ONLINE|ON_TRIP|OFFLINE|SUSPENDED
    average_rating NUMERIC(3,2) NOT NULL DEFAULT 5.00,
    jobs_completed INT NOT NULL DEFAULT 0,
    tenure_start_date DATE,
    notes TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_drivers_tenant ON drivers(tenant_id);
CREATE INDEX idx_drivers_firebase ON drivers(firebase_uid);

